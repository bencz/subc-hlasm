/*
 * ============================================================================
 * SECTION: Conditional Branch Operations
 * ============================================================================
 */

static void cgs370_brcond(char *branch_inst, int n, int is_unsigned) {
    int lab;
    
    lab = label();
    
    /* Load second operand from stack if needed */
    if (empty == Q_type) {
        cgs370_pop2();
    } else {
        cgs370_load2();
    }
    
    /* Compare registers */
    if (is_unsigned) {
        gen("         CLR   2,3");
    } else {
        gen("         CR    2,3");
    }
    
    /* Jump over the branch if condition is FALSE */
    char buf[64];
    sprintf(buf, "         %s   %c%d", branch_inst, LPREFIX, lab);
    gen(buf);
    
    /* Take the branch */
    lgen("%s B     %c%d", "        ", n);
    
    genlab(lab);
}

void cgs370_breq(int n)  { cgs370_brcond("BE", n, 0); }
void cgs370_brne(int n)  { cgs370_brcond("BNE", n, 0); }
void cgs370_brlt(int n)  { cgs370_brcond("BL", n, 0); }
void cgs370_brgt(int n)  { cgs370_brcond("BH", n, 0); }
void cgs370_brle(int n)  { cgs370_brcond("BNH", n, 0); }
void cgs370_brge(int n)  { cgs370_brcond("BNL", n, 0); }
void cgs370_brult(int n) { cgs370_brcond("BL", n, 1); }
void cgs370_brugt(int n) { cgs370_brcond("BH", n, 1); }
void cgs370_brule(int n) { cgs370_brcond("BNH", n, 1); }
