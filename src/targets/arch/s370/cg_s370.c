void cgs370_call(char *s) {
    if (TARGET_OS == OS_MVS) {
        /* MVS: LA 1,param_area + L 15,=A(func) + BALR + LR 2,15 */
        ngen("%s LA    1,%d(,13)", "        ", Stk);
        sgen("%s L     15,=A(%s)", "        ", s);
        gen("         BALR  14,15");
        gen("         LR    2,15");
    } else {
        sgen("%s L     15,=V(%s)", "        ", s);
        gen("         BALR  14,15");
    }
}

