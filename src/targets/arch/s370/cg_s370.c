void cgs370_stack(int n) {
    if (TARGET_OS == OS_MVS) {
        /* MVS: n is the size of local variables, add to Stk */
        ngen("%s A     11,=F'%d'", "        ", n);
        Stk += n;
    } else {
        ngen("%s A     11,=F'%d'", "        ", n);
        Stk -= n;
    }
}

void cgs370_entry(int lsize, int nparams) {
    char buf[128];
    int frame;
    (void)nparams;  /* Not used for S/370 */
    
    if (TARGET_OS == OS_MVS) {
        /* MVS frame calculation:
         * 72 bytes: save area (R14-R12)
         * 16 bytes: reserved area
         * lsize bytes: local variables
         * Round up to multiple of 8 for alignment
         */
        frame = 88 + lsize;
        frame = (frame + 7) & ~7;  /* Align to 8 bytes */
        
        /* MVS-style prologue similar to GCCMVS using PDPPRLG macro */
        sprintf(buf, "* X-func %s prologue", Func_name);
        gen(buf);
        sprintf(buf, "%-8s PDPPRLG CINDEX=%d,FRAME=%d,BASER=12,ENTRY=YES",
                Func_name, Func_idx, frame);
        gen(buf);
        sprintf(buf, "         B     @@FEN%d", Func_idx);
        gen(buf);
        gen("         LTORG");
        sprintf(buf, "@@FEN%d   EQU   *", Func_idx);
        gen(buf);
        gen("         DROP  12");
        gen("         BALR  12,0");
        gen("         USING *,12");
        sprintf(buf, "@@PG%d    EQU   *", Func_idx);
        gen(buf);
        gen("         LR    11,1");      /* 11 = parameter list pointer */
        sprintf(buf, "         L     10,=A(@@PGT%d)", Func_idx);
        gen(buf);
        sprintf(buf, "* Function %s code", Func_name);
        gen(buf);
    } else {
        /* Generic S/370 prologue */
        gen("         STM   14,12,12(13)");
        gen("         LR    12,15");
        gen("         USING *,12");
        gen("         LA    11,72(,13)");
        gen("         ST    13,4(,11)");
        gen("         ST    11,8(,13)");
        gen("         LR    13,11");
    }
    if (TARGET_OS == OS_MVS) {
        Stk = 88;  /* MVS: Start after save area (72) + reserved (16) */
    } else {
        Stk = 72;  /* Start after save area */
    }
}

void cgs370_exit(void) {
    char buf[128];
    
    if (TARGET_OS == OS_MVS) {
        /* MVS-style epilogue - return value in 15 */
        gen("         LR    15,2");      /* Move return value to 15 */
        sprintf(buf, "* Function %s epilogue", Func_name);
        gen(buf);
        gen("         PDPEPIL");
        /* Generate literal pool */
        sprintf(buf, "* Function %s literal pool", Func_name);
        gen(buf);
        gen("         DS    0F");
        gen("         LTORG");
        /* Generate page table */
        sprintf(buf, "* Function %s page table", Func_name);
        gen(buf);
        gen("         DS    0F");
        sprintf(buf, "@@PGT%d   EQU   *", Func_idx);
        gen(buf);
        sprintf(buf, "         DC    A(@@PG%d)", Func_idx);
        gen(buf);
        Func_idx++;
    } else {
        /* Generic S/370 epilogue */
        gen("         L     13,4(,13)");
        gen("         LM    14,12,12(13)");
        gen("         BR    14");
    }
}

