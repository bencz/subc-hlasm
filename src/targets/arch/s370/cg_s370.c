/*
 * ============================================================================
 * SECTION: Stack Operations
 * ============================================================================
 *
 * Note: S/370 stack grows upward. We use a software stack pointed by 11.
 */

static int Stk = 0;  /* Stack pointer offset */

void cgs370_push(void) {
    if (TARGET_OS == OS_MVS) {
        /* MVS: use R13 for parameter area */
        ngen("%s ST    2,%d(,13)", "        ", Stk);
    } else {
        ngen("%s ST    2,%d(,11)", "        ", Stk);
    }
    Stk += 4;
}

void cgs370_pushlit(int n) {
    ngen("%s L     0,=F'%d'", "        ", n);
    if (TARGET_OS == OS_MVS) {
        /* MVS: use R13 for parameter area */
        ngen("%s ST    0,%d(,13)", "        ", Stk);
    } else {
        ngen("%s ST    0,%d(,11)", "        ", Stk);
    }
    Stk += 4;
}

void cgs370_pop2(void) {
    Stk -= 4;
    if (TARGET_OS == OS_MVS) {
        ngen("%s L     3,%d(,13)", "        ", Stk);
    } else {
        ngen("%s L     3,%d(,11)", "        ", Stk);
    }
}

void cgs370_swap(void) {
    gen("         LR    0,2");
    gen("         LR    2,3");
    gen("         LR    3,0");
}

void cgs370_popptr(void) {
    Stk -= 4;
    if (TARGET_OS == OS_MVS) {
        ngen("%s L     3,%d(,13)", "        ", Stk);
        return;
    }
    ngen("%s L     0,%d(,11)", "        ", Stk);
}

