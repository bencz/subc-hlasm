static int Func_idx = 0;    /* Function index for MVS labels */
static char Func_name[64];  /* Current function name */
static int Is_main = 0;     /* Flag for main function */

void cgs370_prelude(void) {
    Func_idx = 0;
    Is_main = 0;
    if (TARGET_OS == OS_MVS) {
        genraw("         COPY  PDPTOP\n");
        genraw("         CSECT\n");
        gen("* Program text area");
        gen("         DS    0F");
    } else {
        gen("*");
        gen("* SubC Generated Code for IBM System/370");
        gen("*");
        gen("         PRINT NOGEN");
    }
}

void cgs370_postlude(void) {
    if (TARGET_OS == OS_MVS) {
        genraw("         END   @@MAIN\n");
    } else {
        gen("         END");
    }
}

void cgs370_public(char *s) {
    /* Save function name for use in entry/exit */
    strncpy(Func_name, s, sizeof(Func_name) - 1);
    Func_name[sizeof(Func_name) - 1] = '\0';
    
    /* Check if this is main */
    if (strcmp(s, "Cmain") == 0 || strcmp(s, "main") == 0) {
        Is_main = 1;
        if (TARGET_OS == OS_MVS) {
            gen("         DS    0F");
            gen("         COPY  PDPMAIN");
        }
    } else {
        Is_main = 0;
    }
    
    /* For non-MVS, generate ENTRY directive */
    if (TARGET_OS != OS_MVS) {
        sgen("%s ENTRY %s", "", s);
    }
}

void cgs370_name(char *s) {
    /* Generate data label */
    if (TARGET_OS == OS_MVS) {
        char buf[64];
        sprintf(buf, "%-8s EQU   *", s);
        gen(buf);
    } else {
        sgen("%s:", s, "");
    }
}

void cgs370_funcname(char *s) {
    /* For MVS, function label is generated by entry with PDPPRLG */
    if (TARGET_OS == OS_MVS) {
        return;
    }
    sgen("%s:", s, "");
}

